public class Literals {
    public static void main(String[] args) {
        // Integer Literal
        int intLiteral = 100;
        System.out.println("Integer Literal: " + intLiteral);

        // Long Literal (suffix 'L' or 'l' to denote long type)
        long longLiteral = 100000L;
        System.out.println("Long Literal: " + longLiteral);

        // Short Literal
        short shortLiteral = 1000;
        System.out.println("Short Literal: " + shortLiteral);

        // Floating-point Literal. (BY DEFAULT, decimal numbers are considered double in Java)
        float floatLiteral = 99.99f;
        System.out.println("Floating-point Literal: " + floatLiteral);











        // double Literal
        double doubleLiteral = 12345.6789;
        System.out.println("Double Literal: " + doubleLiteral);

        // Character Literal
        char charLiteral = 'A';
        System.out.println("Character Literal: " + charLiteral);

        // String Literal
        String stringLiteral = "Hello, Java!";
        System.out.println("String Literal: " + stringLiteral);

        // Boolean Literal
        boolean boolLiteral = true;
        System.out.println("Boolean Literal: " + boolLiteral);
    }
}

// In Java, literals are fixed values that are directly represented in the code.
// They can be of various types, including integer literals, floating-point
// literals, character literals, string literals, and boolean literals.



